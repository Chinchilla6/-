RETURNS trigger LANGUAGE plpgsql SET search_path=public AS $$
BEGIN NEW.updated_at=now(); RETURN NEW; END; $$;

DROP TRIGGER IF EXISTS trg_exercise_relationship_updated_at ON public.exercise_relationships;
CREATE TRIGGER trg_exercise_relationship_updated_at BEFORE UPDATE ON public.exercise_relationships
FOR EACH ROW EXECUTE FUNCTION public.app_set_updated_at();

CREATE OR REPLACE FUNCTION public.audit_exercise_relationship()
RETURNS trigger LANGUAGE plpgsql SET search_path=public AS $$
BEGIN
  INSERT INTO public.exercise_relationship_audit(relationship_id,action,actor_id,old_row,new_row)
  VALUES(COALESCE(NEW.id,OLD.id),TG_OP,NULLIF(current_setting('app.relationship_actor',true),'')::uuid,
    CASE WHEN TG_OP IN ('UPDATE','DELETE') THEN to_jsonb(OLD) END,
    CASE WHEN TG_OP IN ('INSERT','UPDATE') THEN to_jsonb(NEW) END);
  RETURN COALESCE(NEW,OLD);
END; $$;

DROP TRIGGER IF EXISTS trg_exercise_relationship_audit ON public.exercise_relationships;
CREATE TRIGGER trg_exercise_relationship_audit AFTER INSERT OR UPDATE OR DELETE ON public.exercise_relationships
FOR EACH ROW EXECUTE FUNCTION public.audit_exercise_relationship();

CREATE OR REPLACE FUNCTION public.protect_reviewed_exercise_relationship()
RETURNS trigger LANGUAGE plpgsql SET search_path=public AS $$
BEGIN
  IF OLD.review_status='REVIEWED' AND COALESCE(current_setting('app.relationship_review_edit',true),'')<>'on' THEN
    RAISE EXCEPTION 'REVIEWED exercise relationships may only be changed through the explicit review workflow';
  END IF;
  RETURN NEW;
END; $$;

DROP TRIGGER IF EXISTS trg_protect_reviewed_exercise_relationship ON public.exercise_relationships;
CREATE TRIGGER trg_protect_reviewed_exercise_relationship BEFORE UPDATE OR DELETE ON public.exercise_relationships
FOR EACH ROW EXECUTE FUNCTION public.protect_reviewed_exercise_relationship();

CREATE OR REPLACE FUNCTION public.review_exercise_relationship(
  p_relationship_id bigint,p_action text,p_reviewer uuid,p_patch jsonb DEFAULT '{}'::jsonb,p_rejection_reason text DEFAULT NULL
) RETURNS public.exercise_relationships
LANGUAGE plpgsql SECURITY INVOKER SET search_path=public AS $$
DECLARE v_row public.exercise_relationships; v_action text:=upper(p_action);
BEGIN
  IF p_reviewer IS NULL THEN RAISE EXCEPTION 'reviewer is required'; END IF;
  IF v_action NOT IN ('APPROVE','REJECT','EDIT') THEN RAISE EXCEPTION 'unsupported review action: %',p_action; END IF;
  PERFORM set_config('app.relationship_review_edit','on',true);
  PERFORM set_config('app.relationship_actor',p_reviewer::text,true);
  IF v_action='APPROVE' THEN
    UPDATE public.exercise_relationships SET review_status='REVIEWED',reviewed_by=p_reviewer,reviewed_at=now(),rejection_reason=NULL
    WHERE id=p_relationship_id RETURNING * INTO v_row;
  ELSIF v_action='REJECT' THEN
    UPDATE public.exercise_relationships SET review_status='REJECTED',reviewed_by=p_reviewer,reviewed_at=now(),rejection_reason=p_rejection_reason
    WHERE id=p_relationship_id RETURNING * INTO v_row;
  ELSE
    UPDATE public.exercise_relationships SET
      relationship_type=COALESCE(p_patch->>'relationship_type',relationship_type),
      progression_dimension=CASE WHEN p_patch?'progression_dimension' THEN ARRAY(SELECT jsonb_array_elements_text(p_patch->'progression_dimension')) ELSE progression_dimension END,
      difficulty_delta=CASE WHEN p_patch?'difficulty_delta' THEN p_patch->'difficulty_delta' ELSE difficulty_delta END,
      required_conditions=CASE WHEN p_patch?'required_conditions' THEN p_patch->'required_conditions' ELSE required_conditions END,
      contraindications=CASE WHEN p_patch?'contraindications' THEN ARRAY(SELECT jsonb_array_elements_text(p_patch->'contraindications')) ELSE contraindications END,
      confidence=COALESCE((p_patch->>'confidence')::numeric,confidence),
      evidence_level=CASE WHEN p_patch?'evidence_level' THEN NULLIF(p_patch->>'evidence_level','') ELSE evidence_level END,
      evidence_source=CASE WHEN p_patch?'evidence_source' THEN ARRAY(SELECT jsonb_array_elements_text(p_patch->'evidence_source')) ELSE evidence_source END,
      ai_reason=COALESCE(p_patch->>'ai_reason',ai_reason),notes=CASE WHEN p_patch?'notes' THEN p_patch->>'notes' ELSE notes END,
      review_status='AUTO_SUGGESTED',reviewed_by=NULL,reviewed_at=NULL,rejection_reason=NULL
    WHERE id=p_relationship_id RETURNING * INTO v_row;
  END IF;
  PERFORM set_config('app.relationship_review_edit','off',true);
  PERFORM set_config('app.relationship_actor','',true);
  IF v_row.id IS NULL THEN RAISE EXCEPTION 'relationship not found'; END IF;
  RETURN v_row;
END; $$;
