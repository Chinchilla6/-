CREATE OR REPLACE VIEW public.exercise_knowledge_view WITH (security_invoker=true) AS
SELECT e.id exercise_id,t.name name_en,e.category_name,r.movement_family,r.movement_pattern,r.training_intents,r.primary_training_intent,
 r.strength_demand,r.stability_demand,r.coordination_demand,r.balance_demand,r.rom_demand,r.mobility_demand,r.load_potential,
 r.support_level,r.laterality,r.kinetic_chain,r.equipment_level,r.skill_level,r.strength_level,r.mobility_requirement,
 r.classification_status,r.classification_reason,COALESCE(pm.primary_muscles,'{}') primary_muscles,
 COALESCE(sm.secondary_muscles,'{}') secondary_muscles,COALESCE(eq.equipment,'{}') equipment
FROM public.wger_exercises e LEFT JOIN public.rehab_exercise_metadata r ON r.exercise_id=e.id
LEFT JOIN LATERAL(SELECT wt.name FROM public.wger_exercise_translations wt WHERE wt.exercise_id=e.id AND wt.language_id=2 ORDER BY wt.id LIMIT 1)t ON true
LEFT JOIN LATERAL(SELECT array_agg(DISTINCT m.name ORDER BY m.name) primary_muscles FROM public.wger_exercise_muscles em JOIN public.wger_muscles m ON m.id=em.muscle_id WHERE em.exercise_id=e.id AND em.role='primary')pm ON true
LEFT JOIN LATERAL(SELECT array_agg(DISTINCT m.name ORDER BY m.name) secondary_muscles FROM public.wger_exercise_muscles em JOIN public.wger_muscles m ON m.id=em.muscle_id WHERE em.exercise_id=e.id AND em.role='secondary')sm ON true
LEFT JOIN LATERAL(SELECT array_agg(DISTINCT q.name ORDER BY q.name) equipment FROM public.wger_exercise_equipment we JOIN public.wger_equipment q ON q.id=we.equipment_id WHERE we.exercise_id=e.id)eq ON true;
GRANT SELECT ON public.exercise_knowledge_view TO anon,authenticated;

CREATE OR REPLACE VIEW public.exercise_graph_validation WITH (security_invoker=true) AS
SELECT 'CIRCULAR_PROGRESSION'::text issue_type,a.id relationship_id,a.from_exercise_id exercise_id,
 jsonb_build_object('from',a.from_exercise_id,'to',a.to_exercise_id,'reverse_edge',b.id) details
FROM public.exercise_relationships a JOIN public.exercise_relationships b ON b.from_exercise_id=a.to_exercise_id AND b.to_exercise_id=a.from_exercise_id
 AND b.relationship_type='PROGRESSION' AND b.review_status IN('AUTO_SUGGESTED','REVIEWED')
WHERE a.relationship_type='PROGRESSION' AND a.review_status IN('AUTO_SUGGESTED','REVIEWED') AND a.id<b.id
UNION ALL
SELECT 'NO_REVIEWED_PROGRESSION',NULL::bigint,r.exercise_id,jsonb_build_object('family',r.movement_family,'pattern',r.movement_pattern)
FROM public.rehab_exercise_metadata r WHERE r.movement_family IN('GLUTE','HIP') AND r.primary_training_intent IN('STRENGTH','HYPERTROPHY','MOTOR_CONTROL','ACTIVATION','BALANCE','POWER')
 AND r.classification_status<>'REJECTED' AND NOT EXISTS(SELECT 1 FROM public.exercise_relationships er WHERE er.from_exercise_id=r.exercise_id AND er.relationship_type='PROGRESSION' AND er.review_status='REVIEWED')
UNION ALL
SELECT 'NO_REVIEWED_REGRESSION',NULL::bigint,r.exercise_id,jsonb_build_object('family',r.movement_family,'pattern',r.movement_pattern)
FROM public.rehab_exercise_metadata r WHERE r.movement_family IN('GLUTE','HIP') AND r.primary_training_intent IN('STRENGTH','HYPERTROPHY','MOTOR_CONTROL','ACTIVATION','BALANCE','POWER')
 AND r.classification_status<>'REJECTED' AND NOT EXISTS(SELECT 1 FROM public.exercise_relationships er WHERE er.from_exercise_id=r.exercise_id AND er.relationship_type='REGRESSION' AND er.review_status='REVIEWED');
