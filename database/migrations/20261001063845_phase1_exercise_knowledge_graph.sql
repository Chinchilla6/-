CREATE TABLE IF NOT EXISTS public.exercise_relationships (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_exercise_id bigint NOT NULL REFERENCES public.wger_exercises(id) ON DELETE CASCADE,
  to_exercise_id bigint NOT NULL REFERENCES public.wger_exercises(id) ON DELETE CASCADE,
  relationship_type text NOT NULL,
  progression_dimension text[] NOT NULL DEFAULT '{}',
  difficulty_delta jsonb NOT NULL DEFAULT '{}'::jsonb,
  required_conditions jsonb NOT NULL DEFAULT '{}'::jsonb,
  contraindications text[] NOT NULL DEFAULT '{}',
  confidence numeric(4,3),
  evidence_level text,
  evidence_source text[] NOT NULL DEFAULT '{}',
  review_status text NOT NULL DEFAULT 'AUTO_SUGGESTED',
  reviewed_by uuid,
  reviewed_at timestamptz,
  rejection_reason text,
  ai_reason text,
  notes text,
  created_by_type text NOT NULL DEFAULT 'AI',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT exercise_relationship_no_self_loop CHECK (from_exercise_id <> to_exercise_id),
  CONSTRAINT exercise_relationship_type_check CHECK (relationship_type IN
    ('PROGRESSION','REGRESSION','ALTERNATIVE','PREPARATION','ACTIVATION','MOBILITY','RELEASE')),
  CONSTRAINT exercise_relationship_dimension_check CHECK (progression_dimension <@ ARRAY[
    'LOAD','VOLUME','ROM','STABILITY','COORDINATION','BALANCE','UNILATERAL','TEMPO',
    'POWER','ENDURANCE','MOTOR_CONTROL','COMPLEXITY']::text[]),
  CONSTRAINT exercise_relationship_review_status_check CHECK
    (review_status IN ('AUTO_SUGGESTED','REVIEWED','REJECTED')),
  CONSTRAINT exercise_relationship_review_requires_reviewer CHECK
    (review_status <> 'REVIEWED' OR (reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)),
  CONSTRAINT exercise_relationship_confidence_range CHECK (confidence IS NULL OR confidence BETWEEN 0 AND 1),
  CONSTRAINT exercise_relationship_evidence_level_check CHECK (evidence_level IS NULL OR evidence_level IN ('A','B','C','D')),
  CONSTRAINT exercise_relationship_unique UNIQUE(from_exercise_id,to_exercise_id,relationship_type)
);

CREATE INDEX IF NOT EXISTS idx_relationship_from_type_status
